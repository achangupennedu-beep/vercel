/**
 * Get the Dukascopy instrument ID for a ticker symbol.
 * Returns undefined if the symbol is not in the 610-instrument list.
 */
export function getDukascopyId(ticker: string): string | undefined {
  return DUKASCOPY_INSTRUMENTS[ticker.toUpperCase()]
}

/**
 * All supported ticker symbols (610 stocks).
 */
export const SUPPORTED_TICKERS: string[] = Object.keys(DUKASCOPY_INSTRUMENTS).filter(
  // De-duplicate aliases (e.g. META and FB both → fbususd)
  (k, _i, arr) =>
    !["FB", "BKNG", "PCLN", "BRKB", "ANTM"].includes(k) ||
    !arr.some(other => other !== k && DUKASCOPY_INSTRUMENTS[other] === DUKASCOPY_INSTRUMENTS[k] && other < k)
)
